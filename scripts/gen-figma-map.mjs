// Builds xui.figma-map.json — every Figma component set, and what it is in XUI.
//
// WHY. Figma's Code Connect would put the real XUI import inside Figma's Dev Mode
// for anyone inspecting a component. It is gated to Organization and Enterprise
// plans, and XUI lives on a Student team, so it cannot be built here. Most of what
// it gives an AGENT is available without it: the mapping from each Figma set to
// its XUI component, and from each Figma axis to its prop, already exists — it
// has been sitting inside check-variant-axes.mjs, used only to fail CI.
//
// This serves it. The figma_to_xui MCP tool reads the file this writes, so an
// agent looking at a Figma node can ask "what is this in XUI?" instead of
// guessing — which is exactly the failure Code Connect exists to prevent.
//
// Both readers use scripts/figma-map.mjs, so the axis gate and the MCP tool cannot
// disagree about what a Figma set maps to.
//
//   node scripts/gen-figma-map.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MAP, NOT_A_PROP, PROP_FOR, OUT_OF_SCOPE, ACCEPTED } from './figma-map.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const snapshot = JSON.parse(fs.readFileSync(path.join(root, 'scripts/figma-axes.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).name;

const sets = snapshot.sets.map((set) => {
  const xui = MAP[set.figma];
  const base = { figma: set.figma, ids: set.ids };

  if (OUT_OF_SCOPE[set.figma]) {
    return { ...base, xui: null, status: 'out-of-scope', note: OUT_OF_SCOPE[set.figma] };
  }
  if (xui === undefined) {
    return { ...base, xui: null, status: 'unmapped', note: 'Not in figma-map.mjs yet.' };
  }
  if (xui === null) {
    return {
      ...base,
      xui: null,
      status: 'not-built',
      note: 'Drawn in Figma with no XUI component. Do not build a local one; report it — see get_xui_status.',
    };
  }

  const props = [];
  const states = [];
  const accepted = [];
  for (const [axis, values] of Object.entries(set.axes)) {
    const key = `${xui}.${axis}`;
    if (NOT_A_PROP.has(axis)) {
      // A hover or disabled state is CSS and the DOM. Figma draws it as a
      // variant only because a static frame has no other way to show it.
      states.push({ axis, values });
    } else if (ACCEPTED[key]) {
      accepted.push({ axis, values, why: ACCEPTED[key] });
    } else {
      props.push({ axis, prop: PROP_FOR[axis] ?? null, values });
    }
  }

  return {
    ...base,
    xui,
    status: 'mapped',
    import: `import { ${xui} } from '${pkg}';`,
    props,
    states,
    accepted,
  };
});

const out = {
  $comment:
    'AUTO-GENERATED by scripts/gen-figma-map.mjs from scripts/figma-map.mjs and scripts/figma-axes.json. ' +
    'Every Figma component set in XUI and what it is in code. Read by the figma_to_xui MCP tool. ' +
    'A stand-in for Figma Code Connect, which is gated to Organization and Enterprise plans.',
  source: snapshot.source,
  count: sets.length,
  mapped: sets.filter((s) => s.status === 'mapped').length,
  sets,
};

fs.writeFileSync(path.join(root, 'xui.figma-map.json'), JSON.stringify(out, null, 2) + '\n');
const by = (st) => sets.filter((s) => s.status === st).length;
console.log(
  `figma map: ${sets.length} sets — ${by('mapped')} mapped, ${by('not-built')} not built, ` +
    `${by('out-of-scope')} out of scope -> xui.figma-map.json`,
);

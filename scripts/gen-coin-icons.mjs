// Generates src/icons/coin-icons.tsx from the XUI Figma "Coin Type" component set.
//
// Input is scripts/coin-icon-data/: an index.json listing every icon with its
// Figma node id, category and name, plus one <node-id>.svg per icon exported
// straight from the file. The SVGs are Figma's own bytes — nothing here retypes
// a path, so a re-export is the only way this drifts.
//
// These are NOT Icons v2 and do not go through gen-icons.mjs:
//   - one shape, not four tones
//   - a fixed 40x40 badge, not a 24px glyph
//   - their own palette, NOT currentColor and NOT bound to any XUI variable
//     (see the header this writes into the output, and Guides > Status)
//
// Run: node scripts/gen-coin-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(root, 'scripts', 'coin-icon-data');
const out = path.join(root, 'src', 'icons', 'coin-icons.tsx');

const pascal = (s) =>
  s
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');

/** `clip-path` -> `clipPath`; `data-*`/`aria-*` stay as authored. */
const camel = (n) => (/^(data|aria)-/.test(n) ? n : n.replace(/-([a-z])/g, (_, c) => c.toUpperCase()));

function attrsToProps(raw) {
  let out = '';
  for (const [, name, value] of raw.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
    // Figma exports its layer names as ids ("Vector", "Frame 27498"). They are
    // decorative and identical across all 48, so a gallery page would carry 48
    // copies of id="Vector". Referenced ids (clip paths) are kept and renamed
    // by nsIds() before this runs.
    if (name === 'id' && !/^clip/.test(value)) continue;
    out += ` ${camel(name)}=${JSON.stringify(value)}`;
  }
  return out;
}

const TAG = /<(\/)?([a-zA-Z][a-zA-Z0-9]*)((?:\s+[a-zA-Z-]+="[^"]*")*)\s*(\/)?>/g;

function markupToJsx(markup, pad) {
  const lines = [];
  let depth = 0;
  for (const [, closing, name, attrs, selfClose] of markup.matchAll(TAG)) {
    if (closing) {
      lines.push(pad + '  '.repeat(--depth) + `</${name}>`);
      continue;
    }
    const open = pad + '  '.repeat(depth) + `<${name}${attrsToProps(attrs)}`;
    if (selfClose) lines.push(open + ' />');
    else {
      lines.push(open + '>');
      depth++;
    }
  }
  if (depth !== 0) throw new Error(`unbalanced SVG markup: ${markup.slice(0, 80)}`);
  return lines.join('\n');
}

/**
 * Namespace every referenced id with the component's own name. Figma's clip ids
 * already carry the node id so they happen not to collide today, but that is an
 * accident of the export and two icons re-exported together could share one.
 */
function nsIds(svg, ns) {
  const ids = new Set([...svg.matchAll(/id="(clip[^"]*)"/g)].map((m) => m[1]));
  for (const id of ids) {
    svg = svg.replaceAll(`id="${id}"`, `id="${id}_${ns}"`).replaceAll(`url(#${id})`, `url(#${id}_${ns})`);
  }
  return svg;
}

/**
 * The inner markup of the `<g id="Property 1=...">` group — the icon, without
 * the component-set chrome Figma renders around it. Walks <g> depth rather than
 * regex-matching the close, since the group nests several levels deep.
 */
function iconGroup(svg, label) {
  const start = svg.search(/<g id="Property 1=/);
  if (start === -1) throw new Error(`${label}: no component group in the export`);
  const open = svg.indexOf('>', start) + 1;

  let depth = 1;
  const tags = /<(\/?)g\b[^>]*>/g;
  tags.lastIndex = open;
  for (let m; (m = tags.exec(svg)); ) {
    depth += m[1] ? -1 : 1;
    if (depth === 0) return svg.slice(open, m.index).trim();
  }
  throw new Error(`${label}: component group never closes`);
}

/** The <defs> block, if any — clip paths referenced from inside the group. */
function defsOf(svg) {
  const m = /<defs>[\s\S]*?<\/defs>/.exec(svg);
  return m ? '\n' + m[0] : '';
}

const index = JSON.parse(fs.readFileSync(path.join(dataDir, 'index.json'), 'utf8'));

const seen = new Set();
const registry = [];
const palette = new Set();

let body = `// AUTO-GENERATED by scripts/gen-coin-icons.mjs from the XUI Figma "Coin Type"\n`;
body += `// component set (${index.source.file}, node ${index.source.node}). Do not edit by hand.\n`;
body += `//\n`;
body += `// xui-lint-ignore-file — brand artwork. Every colour below is a raw hex read\n`;
body += `// straight from Figma: the set binds NO variables, and its palette (#4F677E\n`;
body += `// disc, #26D0FF / #2AFF95 glyph) has no equivalent in the XUI ramp. So unlike\n`;
body += `// Icons v2 these do not follow the theme. That is faithful to the file, not a\n`;
body += `// choice made here — it is recorded as an open question on Guides > Status.\n`;
body += `import { createCoinIcon } from './createCoinIcon';\n`;
body += `import type { ComponentType } from 'react';\n`;
body += `import type { CoinIconProps } from './createCoinIcon';\n\n`;

let currentCat = null;
for (const icon of index.icons) {
  const file = path.join(dataDir, icon.id.replace(':', '-') + '.svg');
  if (!fs.existsSync(file)) throw new Error(`missing export for ${icon.name} (${icon.id})`);

  let name = pascal(icon.name) + 'Coin';
  if (seen.has(name)) throw new Error(`duplicate component name ${name} — fix index.json`);
  seen.add(name);

  let svg = fs.readFileSync(file, 'utf8');
  svg = nsIds(svg, name);

  // Figma renders a COMPONENT inside its set, so every export arrives wrapped in
  // the set's chrome: a #AAAAAA backing rect, a white board and the purple
  // #9747FF dashed frame, all 1413x460 at negative offsets. Take only the
  // `<g id="Property 1=...">` group, which is the icon itself, plus the <defs>
  // that its clip paths point at.
  const inner = iconGroup(svg, icon.name) + defsOf(svg);
  // Scanned after slicing, so the reported palette is the artwork's own and not
  // the component-set chrome's #AAAAAA / #9747FF.
  for (const [, hex] of inner.matchAll(/(#[0-9a-fA-F]{6})/g)) palette.add(hex.toUpperCase());

  if (icon.cat !== currentCat) {
    currentCat = icon.cat;
    body += `// ---- ${currentCat} ----\n`;
  }
  body += `export const ${name} = /*#__PURE__*/ createCoinIcon(${JSON.stringify(name)}, (\n`;
  body += `  <>\n${markupToJsx(inner, '    ')}\n  </>\n));\n\n`;
  registry.push({ name, cat: icon.cat, label: icon.name });
}

body += `export type CoinIconName =\n${registry.map((r) => `  | ${JSON.stringify(r.name)}`).join('\n')};\n\n`;
body += `/** Every coin icon, grouped as the Figma set groups them. Drives the gallery. */\n`;
body += `export const coinIconCategories: Record<string, CoinIconName[]> = {\n`;
for (const cat of [...new Set(registry.map((r) => r.cat))]) {
  body += `  ${JSON.stringify(cat)}: [\n`;
  for (const r of registry.filter((x) => x.cat === cat)) body += `    ${JSON.stringify(r.name)},\n`;
  body += `  ],\n`;
}
body += `};\n\n`;
body += `export const coinIcons: Record<CoinIconName, ComponentType<CoinIconProps>> = {\n`;
for (const r of registry) body += `  ${r.name},\n`;
body += `};\n`;

fs.writeFileSync(out, body);

const byCat = registry.reduce((a, r) => ((a[r.cat] = (a[r.cat] ?? 0) + 1), a), {});
console.log(
  `coin icons: ${registry.length} (${Object.entries(byCat).map(([k, v]) => `${k} ${v}`).join(', ')}) ` +
    `-> ${path.relative(root, out)}`,
);
console.log(`  palette: ${[...palette].sort().join(' ')}`);
